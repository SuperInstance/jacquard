"""Generate spec/vectors/vectors.json.

Golden vectors pin the wire format and the kernel's behaviour on
a fixed scenario. They are generated by the implementation and
checked two ways in tests/test_vectors.py: by re-deriving them
with the implementation, and by recomputing one entry hash from
a hand-written canonical string, independently of the canonical
serialiser.
"""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from jacquard import Log, Sequencer, fold, make_envelope, envelope_hash
from jacquard.canonical import SPEC_SEAL

DOUBLE = {"name": "double",
          "signature": {"ins": ["int"], "outs": ["int"]},
          "body": ["dup", "add"],
          "examples": [{"args": [21], "expect": [42]}]}

DISPATCH_JOB = {"name": "dispatch-job",
                "signature": {"ins": ["map"], "outs": []},
                "body": ["dispatch"],
                "examples": [{"args": [{"job": "job-1"}],
                              "requests": ["dispatch"]}]}


def main():
    vectors = {"spec_seal": SPEC_SEAL}

    # A short entry chain in the log format.
    log = Log()
    e0 = log.append("sense", {"producer": "operator",
                              "name": "gpu-foreign", "value": False})
    seq = Sequencer()
    stored_double = seq.dictionary.define(DOUBLE)
    e1 = log.append("definition", {"producer": "operator",
                                   "definition": stored_double})
    state = fold(log.entries)
    e2 = log.append("checkpoint", {"name": "after-two",
                                   "state_hash": state.state_hash()})
    # A fourth entry whose body carries non-ASCII text, so the
    # canonical string-escaping rule (spec section 1) is exercised
    # by the vectors and not merely stated.
    e3 = log.append("checkpoint", {"name": "café-☃",
                                   "state_hash": state.state_hash()})
    vectors["entries"] = [
        {"seq": e["seq"], "kind": e["kind"], "body": e["body"],
         "hash": e["hash"]} for e in (e0, e1, e2, e3)]

    # An envelope and its id.
    env = make_envelope("operator", "proposal",
                        {"requests": [{"verb": "write",
                                       "args": ["answer", 42]}]},
                        ["write"], "vectors-1")
    vectors["envelope"] = {"envelope": env, "id": envelope_hash(env)}

    # Definitions and their computed effects.
    seq2 = Sequencer()
    seq2.submit(make_envelope("operator", "definition", DOUBLE, [], "v-d1"))
    seq2.submit(make_envelope("operator", "definition", DISPATCH_JOB,
                              ["dispatch"], "v-d2"))
    vectors["definitions"] = [
        {"definition": d,
         "stored": seq2.state.dictionary[d["name"]][-1]["definition"]}
        for d in (DOUBLE, DISPATCH_JOB)]

    # A folded state after one executed write.
    seq2.submit(make_envelope(
        "operator", "proposal",
        {"requests": [{"verb": "write", "args": ["answer", 42],
                       "outputs": ["o-42"]}]},
        ["write"], "v-p1"))
    vectors["state"] = {"units": seq2.state.units,
                        "state_hash": seq2.state.state_hash()}

    out = os.path.join(os.path.dirname(__file__), "..",
                       "spec", "vectors", "vectors.json")
    with open(out, "w", encoding="utf-8") as fh:
        json.dump(vectors, fh, sort_keys=True, indent=1)
        fh.write("\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
