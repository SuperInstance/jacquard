"""Generate spec/vectors/vectors.json.

Golden vectors pin the wire format and the kernel's behaviour on
a fixed scenario. They are generated by the implementation and
checked two ways in tests/test_vectors.py: by re-deriving them
with the implementation, and by recomputing one entry hash from
a hand-written canonical string, independently of the canonical
serialiser. The anchor section (spec 15) is signed here directly
with the `cryptography` package under a published test key, so
the generator — like the anchor tooling, and unlike the kernel —
depends on it.
"""
import hashlib
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from jacquard import Log, Sequencer, fold, make_envelope, envelope_hash
from jacquard.senses import compute_sense
from jacquard.canonical import SPEC_SEAL, SPEC_VERSION, canonical, hash_of

DOUBLE = {"name": "double",
          "signature": {"ins": ["int"], "outs": ["int"]},
          "body": ["dup", "add"],
          "examples": [{"args": [21], "expect": [42]}]}

DISPATCH_JOB = {"name": "dispatch-job",
                "signature": {"ins": ["map"], "outs": []},
                "body": ["dispatch"],
                "examples": [{"args": [{"job": "job-1"}],
                              "requests": ["dispatch"]}]}


def _exec_entry(log, producer, cls, proposal_id, unit, value):
    """One execution entry applying a single write -- the only
    kind the sense cases need: contention reads committed units
    (folded from applied writes); authority scans executions."""
    return log.append("execution", {
        "producer": producer, "class": cls, "proposal_id": proposal_id,
        "applied": [{"verb": "write", "args": [unit, value]}],
        "uses": []})


def _booking(bid, producer, seat, start, end, rank):
    return {"id": bid, "box": "thor", "producer": producer,
            "seat": seat, "start": start, "end": end,
            "checkby": None, "status": "active", "rank": rank,
            "asserted_rank": rank}


def _sense_case(sense, subject, entries):
    reading = compute_sense("%s:%s" % (sense, subject), entries,
                            fold(entries))
    return {"entries": entries, "subject": subject,
            "expect": {"value": reading["value"],
                       "method": reading["method"],
                       "as_of_seq": reading["as_of_seq"]}}


def senses_section():
    """Sense-computation vectors (spec 0.3, section 11.3): cases
    built from stated entry lists (mini logs folded by this
    tool). Each case is {"entries", "subject", "expect"} with
    expect {"value", "method", "as_of_seq"}; tests/test_vectors.py
    verifies the section via fold + compute_sense."""
    cases = {"contention": [], "authority": []}

    # Contention: a clear candidate -- committed booking does
    # not overlap the candidate's window.
    log = Log()
    e = [_exec_entry(log, "lane-a", "booking", "sv-bk-1",
                     "booking/thor/bk-1",
                     _booking("bk-1", "lane-a", "gpu", 1000, 1100, 0))]
    cases["contention"].append(_sense_case(
        "contention", "thor/zcode/1200/1300/lane-b/cand-1", e))

    # Contention: two contenders -- the candidate's "box" seat
    # contends with every seat; both committed bookings overlap.
    log = Log()
    e = [_exec_entry(log, "lane-a", "booking", "sv-bk-1",
                     "booking/thor/bk-1",
                     _booking("bk-1", "lane-a", "gpu", 1000, 1200, 1)),
         _exec_entry(log, "lane-c", "booking", "sv-bk-2",
                     "booking/thor/bk-2",
                     _booking("bk-2", "lane-c", "stage", 1150, 1400, 3))]
    cases["contention"].append(_sense_case(
        "contention", "thor/box/1100/1300/lane-b/cand-2", e))

    # Contention: an unclassified-seat candidate -- "zcod" is in
    # neither the exclusive set nor {"detached"}; distinct seats
    # do not contend, so the count is 0 but the seat is reported.
    log = Log()
    e = [_exec_entry(log, "lane-a", "booking", "sv-bk-1",
                     "booking/thor/bk-1",
                     _booking("bk-1", "lane-a", "gpu", 1000, 1200, 0))]
    cases["contention"].append(_sense_case(
        "contention", "thor/zcod/1050/1150/lane-b/cand-3", e))

    # Authority: an ungranted producer -- her own write to
    # authority/mallory lands as an execution, but the producer
    # filter ignores it (the self-grant attack, as a vector).
    log = Log()
    e = [_exec_entry(log, "mallory", "work", "sv-self-grant",
                     "authority/mallory", 99)]
    cases["authority"].append(_sense_case("authority", "mallory", e))

    # Authority: granted, then re-granted lower -- last-wins, so
    # the second grant is a downward revocation: ceiling 2.
    log = Log()
    e = [_exec_entry(log, "operator", "config", "sv-grant-1",
                     "authority/captain", 5),
         _exec_entry(log, "operator", "config", "sv-grant-2",
                     "authority/captain", 2)]
    cases["authority"].append(_sense_case("authority", "captain", e))

    return cases


def main():
    vectors = {"spec_seal": SPEC_SEAL}

    # A short entry chain in the log format.
    log = Log()
    e0 = log.append("sense", {"producer": "operator",
                              "name": "gpu-foreign", "value": False})
    seq = Sequencer()
    stored_double = seq.dictionary.define(DOUBLE)
    e1 = log.append("definition", {"producer": "operator",
                                   "definition": stored_double})
    state = fold(log.entries)
    e2 = log.append("checkpoint", {"name": "after-two",
                                   "state_hash": state.state_hash()})
    # A fourth entry whose body carries non-ASCII text, so the
    # canonical string-escaping rule (spec section 1) is exercised
    # by the vectors and not merely stated.
    e3 = log.append("checkpoint", {"name": "café-☃",
                                   "state_hash": state.state_hash()})
    vectors["entries"] = [
        {"seq": e["seq"], "kind": e["kind"], "body": e["body"],
         "hash": e["hash"]} for e in (e0, e1, e2, e3)]

    # A chain-head anchoring checkpoint (spec 0.5, section 15) over
    # the vector entry chain, issued under a published TEST key.
    # Ed25519 signing is deterministic, so the signature is a
    # stable vector. The seed is recorded in the vectors; this key
    # is a fixture, never an operator key.
    from cryptography.hazmat.primitives.asymmetric.ed25519 import (
        Ed25519PrivateKey)
    from cryptography.hazmat.primitives.serialization import (
        Encoding, NoEncryption, PrivateFormat, PublicFormat)
    test_seed = hashlib.sha256(
        b"jacquard anchor test key - NOT A REAL KEY - vectors only"
    ).digest()
    test_key = Ed25519PrivateKey.from_private_bytes(test_seed)
    test_pub = test_key.public_key().public_bytes(
        Encoding.Raw, PublicFormat.Raw).hex()
    anchor_body = {"format": "jacquard/anchor/1",
                   "log_id": e0["hash"],
                   "label": "golden-vectors",
                   "checkpoint_seq": 0,
                   "log_length": 4,
                   "head_hash": e3["hash"],
                   "spec": SPEC_VERSION,
                   "prev_checkpoint": None}
    anchor_envelope = {"body": anchor_body, "pubkey": test_pub,
                       "sig": test_key.sign(canonical(anchor_body)).hex()}
    vectors["anchor"] = {"test_seed": test_seed.hex(),
                         "envelope": anchor_envelope,
                         "checkpoint_hash": hash_of(anchor_body)}

    # An envelope and its id.
    env = make_envelope("operator", "proposal",
                        {"requests": [{"verb": "write",
                                       "args": ["answer", 42]}]},
                        ["write"], "vectors-1")
    vectors["envelope"] = {"envelope": env, "id": envelope_hash(env)}

    # Definitions and their computed effects.
    seq2 = Sequencer()
    seq2.submit(make_envelope("operator", "definition", DOUBLE, [], "v-d1"))
    seq2.submit(make_envelope("operator", "definition", DISPATCH_JOB,
                              ["dispatch"], "v-d2"))
    vectors["definitions"] = [
        {"definition": d,
         "stored": seq2.state.dictionary[d["name"]][-1]["definition"]}
        for d in (DOUBLE, DISPATCH_JOB)]

    # A folded state after one executed write.
    seq2.submit(make_envelope(
        "operator", "proposal",
        {"requests": [{"verb": "write", "args": ["answer", 42],
                       "outputs": ["o-42"]}]},
        ["write"], "v-p1"))
    vectors["state"] = {"units": seq2.state.units,
                        "state_hash": seq2.state.state_hash()}

    # Sense-computation cases (spec 0.3, section 11.3).
    vectors["senses"] = senses_section()

    out = os.path.join(os.path.dirname(__file__), "..",
                       "spec", "vectors", "vectors.json")
    with open(out, "w", encoding="utf-8") as fh:
        json.dump(vectors, fh, sort_keys=True, indent=1)
        fh.write("\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
